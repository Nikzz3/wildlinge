const base: Record<string, FontGlyph> = Object.fromEntries([
  ...UPPER_A_M, ...UPPER_N_Z, ...LOWER_A_M, ...LOWER_N_Z, ...DIGITS, ...PUNCT_1, ...PUNCT_2, ...SYMBOLS, ...EXTRAS,
]);

function glyph(ch: string): FontGlyph {
  const g = base[ch];
  if (!g) throw new Error(`font: missing base glyph "${ch}"`);
  return g;
}

const SPACE_WIDTH = 4;
const CAP_DOTS = [[0, 1], [0, 3]] as const;
const LOWER_DOTS = [[2, 1], [2, 3]] as const;

export const FONT: FontDef = {
  height: TOP_ROWS + ART_ROWS,
  spacing: 1,
  spaceWidth: SPACE_WIDTH,
  glyphs: {
    ...base,
    ' ': { w: SPACE_WIDTH, rows: Array<string>(TOP_ROWS + ART_ROWS).fill('.'.repeat(SPACE_WIDTH)) },
    Ä: withMarks(glyph('A'), CAP_DOTS),
    Ö: withMarks(glyph('O'), CAP_DOTS),
    Ü: withMarks(glyph('U'), CAP_DOTS),
    ä: withMarks(glyph('a'), LOWER_DOTS),
    ö: withMarks(glyph('o'), LOWER_DOTS),
    ü: withMarks(glyph('u'), LOWER_DOTS),
    é: withMarks(glyph('e'), [[1, 3], [2, 2]]),
  },
};
