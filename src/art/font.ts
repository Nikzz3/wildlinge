import type { FontDef, FontGlyph } from '../core/contracts';

/**
 * WILDLINGE text font: variable-width, 1px strokes, rounded corners.
 *
 * Glyph rows (FONT.height = 12):
 *   0–1   capital umlaut dots / accents
 *   2–9   capitals and digits (8px), ascenders start at 2
 *   4–9   lowercase x-height (lowercase umlaut dots on row 2)
 *   10–11 descenders
 *
 * The art below covers rows 2–11 (10 rows). Each block lists its characters, then the
 * glyph art side by side; tokens are matched to characters by order, so a glyph's
 * width is the length of its tokens.
 */

const ART_ROWS = 10;
const TOP_ROWS = 2;

function block(chars: string, art: string): [string, FontGlyph][] {
  const lines = art.split('\n').filter((l) => l.trim() !== '');
  if (lines.length !== ART_ROWS) throw new Error(`font block "${chars}": expected ${ART_ROWS} rows, got ${lines.length}`);
  const cells = lines.map((l) => l.trim().split(/\s+/));
  const list = [...chars];
  if (cells.some((c) => c.length !== list.length)) throw new Error(`font block "${chars}": token count mismatch`);
  return list.map((ch, i) => {
    const rows = cells.map((c) => c[i] ?? '');
    const w = rows[0]!.length;
    if (w === 0 || rows.some((r) => r.length !== w)) throw new Error(`font glyph "${ch}": ragged rows`);
    return [ch, { w, rows: [...Array<string>(TOP_ROWS).fill('.'.repeat(w)), ...rows] }];
  });
}

/** Copies a glyph and inks the given marks: [row, x] pairs. */
function withMarks(base: FontGlyph, marks: readonly (readonly [number, number])[]): FontGlyph {
  const rows = base.rows.map((r) => [...r]);
  for (const [y, x] of marks) rows[y]![x] = '#';
  return { w: base.w, rows: rows.map((r) => r.join('')) };
}

