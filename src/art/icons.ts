function cureIcon(status: StatusId | 'all'): Bitmap {
  switch (status) {
    case 'all':
      return draw(HERB, HERB_PAL);
    case 'sleep':
      return layered(draw(HERB, HERB_PAL), draw(BLOSSOM, BLOSSOM_PAL));
    case 'burn':
      return draw(TIN, TIN_PAL);
    case 'poison':
      return bottle(VIAL, GREEN);
    case 'paralysis':
      return bottle(VIAL, YELLOW);
  }
}

function gemColors(rate: number): GemColors {
  if (rate >= 255) return GEM_GOLD;
  if (rate >= 1.75) return GEM_VIOLET;
  if (rate >= 1.25) return GEM_BLUE;
  return GEM_TEAL;
}

function canColors(steps: number): CanColors {
  if (steps >= 250) return CAN_PURPLE;
  if (steps >= 150) return CAN_BLUE;
  return CAN_GREEN;
}

function keyItemIcon(id: string): Bitmap {
  const key = id.toLowerCase();
  if (/key|schluessel|schlüssel/.test(key)) return draw(KEY, KEY_PAL);
  if (/letter|brief|note|notiz/.test(key)) return draw(LETTER, LETTER_PAL);
  return draw(PARCEL, PARCEL_PAL);
}

/** 16×16 icon derived from the item's data (exported for sheets/tests; prefer itemIcon). */
export function iconForItem(item: ItemDef): Bitmap {
  const u = item.use;
  switch (u.kind) {
    case 'heal':
      return healIcon(u.hp);
    case 'cure':
      return cureIcon(u.status);
    case 'restore':
      return withSparkle(draw(HEART_FLASK, { ...GLASS, ...CORK, ...ROSE, O: OUTLINE.rose }), true);
    case 'revive':
      return u.fraction >= 1 ? withSparkle(draw(EMBER, EMBER_GOLD), true) : draw(EMBER, EMBER_ORANGE);
    case 'pp':
      return soupIcon(u.amount === 'full');
    case 'crystal':
      return withSparkle(draw(GEM, gemColors(u.rate)), u.rate >= 255);
    case 'repel':
      return draw(SPRAY, { ...SPRAY_CAP, ...canColors(u.steps) });
    case 'candy':
      return draw(HONEYCOMB, HONEYCOMB_PAL);
    case 'none':
      return item.pocket === 'key' ? keyItemIcon(item.id) : draw(POUCH, POUCH_PAL);
  }
}

function findItem(itemId: string): ItemDef | null {
  try {
    return getItem(itemId);
  } catch {
    return null;
  }
}

/** 16×16 bag icon for an item id. Unknown ids get a "?" pouch. */
export function itemIcon(itemId: string): Bitmap {
  return cached(`item:${itemId}`, () => {
    const item = findItem(itemId);
    if (item) return iconForItem(item);
    return layered(draw(POUCH, POUCH_PAL), draw(QUESTION_STAMP, { q: '#5c3c20' }));
  });
}

/** 12×12 crystal for the battle throw/shake animation, coloured like the item's bag icon. */
export function crystalThrowIcon(itemId: string): Bitmap {
  return cached(`throw:${itemId}`, () => {
    const use = findItem(itemId)?.use;
    return draw(GEM_SMALL, use?.kind === 'crystal' ? gemColors(use.rate) : GEM_TEAL);
  });
}

