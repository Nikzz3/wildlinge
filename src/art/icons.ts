function makeIcon(id: IconId): Bitmap {
  switch (id) {
    case 'cursor':
      return bitmapFromRows(shadowed(rowsOf(CURSOR)), INK_ON_LIGHT);
    case 'cursor_light':
      return bitmapFromRows(shadowed(rowsOf(CURSOR)), INK_ON_DARK);
    case 'cursor_hollow':
      return bitmapFromRows(shadowed(rowsOf(CURSOR_HOLLOW)), INK_ON_LIGHT);
    case 'arrow_down':
      return draw(ARROW_DOWN, ARROW_INK);
    case 'arrow_up':
      return draw(ARROW_UP, ARROW_INK);
    case 'emote_exclaim':
      return layered(draw(BUBBLE_ART, BUBBLE), draw(EXCLAIM, { R: '#e83828', r: '#b02018' }));
    case 'emote_question':
      return layered(draw(BUBBLE_ART, BUBBLE), draw(QUESTION, { B: '#3070d8', b: '#2050a0' }));
    case 'emote_heart':
      return layered(draw(BUBBLE_ART, BUBBLE), draw(HEART, { H: '#f04870', h: '#f8b0c0', k: '#b82850' }));
    case 'party_ball':
      return draw(ORB, GEM_TEAL);
    case 'party_ball_status':
      return draw(ORB, ORB_AMBER);
    case 'party_ball_fainted':
      return draw(ORB, ORB_GRAY);
    case 'party_ball_empty':
      return draw(ORB, ORB_EMPTY);
    case 'crystal_throw':
      return draw(GEM_SMALL, GEM_TEAL);
    case 'shadow':
      return draw(SHADOW, { '#': '#18202860' });
    case 'save':
      return draw(FLOPPY, FLOPPY_INK);
  }
}

export function icon(id: IconId): Bitmap {
  return cached(`icon:${id}`, () => {
    const b = makeIcon(id);
    const [w, h] = SIZES[id];
    if (b.w !== w || b.h !== h) throw new Error(`icon "${id}" is ${b.w}×${b.h}, expected ${w}×${h}`);
    return b;
  });
}

