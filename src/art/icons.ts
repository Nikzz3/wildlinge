type Palette = Readonly<Record<string, string>>;

/** Rows of a multi-line art string ('.' = transparent). */
function rowsOf(art: string): string[] {
  return art.split('\n').map((r) => r.trim()).filter((r) => r.length > 0);
}

function draw(art: string, pal: Palette): Bitmap {
  return bitmapFromRows(rowsOf(art), pal);
}

/** Draws the layers on top of each other (all must have the same size as the first). */
function layered(...layers: Bitmap[]): Bitmap {
  const first = layers[0]!;
  const out = createBitmap(first.w, first.h);
  for (const l of layers) blit(out, l, 0, 0);
  return out;
}

/** Empty pixels reachable from the border (4-neighbour flood fill): outside the shape. */
function outside(rows: readonly string[]): boolean[][] {
  const out = rows.map((r) => [...r].map(() => false));
  const h = rows.length;
  const w = rows[0]?.length ?? 0;
  const todo: [number, number][] = [];
  for (let x = 0; x < w; x++) todo.push([x, 0], [x, h - 1]);
  for (let y = 0; y < h; y++) todo.push([0, y], [w - 1, y]);
  for (let next = todo.pop(); next; next = todo.pop()) {
    const [x, y] = next;
    if (rows[y]?.[x] !== '.' || out[y]![x]) continue;
    out[y]![x] = true;
    todo.push([x + 1, y], [x - 1, y], [x, y + 1], [x, y - 1]);
  }
  return out;
}

/** Adds a 1px drop shadow ('s') down-right of the shape (never inside enclosed holes). */
function shadowed(rows: readonly string[]): string[] {
  const out = outside(rows);
  const ink = (x: number, y: number) => (rows[y]?.[x] ?? '.') !== '.';
  return rows.map((row, y) =>
    [...row].map((c, x) => (c === '.' && out[y]![x] && ink(x - 1, y - 1) ? 's' : c)).join(''),
  );
}

const cache = new Map<string, Bitmap>();
function cached(key: string, make: () => Bitmap): Bitmap {
  let b = cache.get(key);
  if (!b) {
    b = make();
    cache.set(key, b);
  }
  return b;
}

